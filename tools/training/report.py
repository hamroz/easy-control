"""Renders the evaluation metrics as Markdown."""


def render(m: dict) -> str:
    classes, t, r = m["classes"], m["test"], m["rules"]
    pct = lambda v: f"{v:.1%}"  # noqa: E731
    lines = [
        "# M3 Evaluation Report — Pose Classifier",
        "",
        f"Generated by `tools/training/train.py` on {m['date']}. Test set = HaGRID **held-out subjects** "
        f"({m['subjects']['test']} people never seen in training), {m['sizes']['test']} matched hands.",
        "",
        "## Headline",
        "",
        "All numbers count every detected hand, the way the app sees it: hands that fail the runtime gate "
        f"(`{m['config']['gate']}`) are `none`, and the app only acts on a pose with probability ≥ {m['threshold']}.",
        "",
        "| Metric (test) | Core ML model | Rules (M2) |",
        "|---|---|---|",
        f"| Accuracy, acting only at ≥ {m['threshold']} | **{pct(t['acted_accuracy'])}** | — |",
        f"| Accuracy, argmax (end to end) | {pct(t['end_to_end_accuracy'])} | {pct(r['end_to_end_accuracy'])} |",
        f"| Accuracy, argmax, gated hands only | {pct(t['gated_accuracy'])} | — |",
        f"| Accuracy on the rules' own 6 classes | — | {pct(r['own_classes_accuracy'])} |",
        f"| When it acts on a gesture, it is right | {pct(t['acted_gesture_precision'])} | — |",
        f"| `none` hands turned into a gesture | {pct(t['none_false_trigger_rate'])} | — |",
        "",
        f"Spec target (≥ 97 % accuracy): judged on **accuracy acting at ≥ {m['threshold']}, end to end** — "
        f"**{'met' if t['acted_accuracy'] >= 0.97 else 'not met'}** ({pct(t['acted_accuracy'])}).",
        "",
        "## Recall per class (test, end to end, acting at the threshold)",
        "",
        "| Class | Recall | Support |",
        "|---|---|---|",
        *[f"| {c} | {t['acted_recall'][c]:.3f} | {t['support'][c]} |" if t["support"][c] else f"| {c} | — | 0 |"
          for c in classes],
        "",
        "## Confusion matrix (test, end to end, acting at the threshold; rows = truth)",
        "",
        "| | " + " | ".join(classes) + " |",
        "|---" * (len(classes) + 1) + "|",
        *[f"| **{c}** | " + " | ".join(str(v) for v in row) + " |" for c, row in zip(classes, t["confusion_acted"])],
        "",
        *(_local_section(m) if m.get("local") else []),
        "## Model and selection",
        "",
        f"Chosen: gate `{m['config']['gate']}`, class-weight power {m['config']['weight_power']}, MLP "
        f"55→{m['config']['hidden'][0]}→{m['config']['hidden'][1]}→{len(classes)} (dropout 0.2, AdamW lr 1e-3, "
        f"early stopping on validation; best epoch {m['training']['best_epoch']}). Standardization is folded into "
        "the model. Training rows include a chirality-flipped copy of every hand so the model does not depend on "
        "Vision's left/right guess; features are aspect-ratio corrected and include absolute orientation.",
        "",
        f"Selection criterion: {m['selection']['criterion']} (validation split only).",
        "",
        "| Gate | Class-weight power | Hidden | Val acc @ threshold | Val gesture precision | Val none→gesture |",
        "|---|---|---|---|---|---|",
        *[f"| {s['gate']} | {s['weight_power']} | {s['hidden'][0]}/{s['hidden'][1]} | {s['val']['acted_accuracy']:.4f} | "
          f"{s['val']['acted_gesture_precision']:.4f} | {s['val']['none_false_trigger_rate']:.4f} |"
          for s in m["selection"]["runs"]],
        "",
        f"Core ML export check: argmax agreement with PyTorch on {m['coreml_check']['n']} test samples = "
        f"{pct(m['coreml_check']['agreement'])}.",
        "",
        "History: an earlier model (before aspect-ratio and orientation features) was reported at 97.8 % on gated "
        "hands only, with argmax; a review showed that overstated live performance, which led to this end-to-end "
        "report. Its initial configuration's test score had also been seen before its validation sweep.",
        "",
        "## Status of the M3 exit criterion",
        "",
        "Spec §9 requires the accuracy **and** false-trigger targets. False actions per hour on real normal-use "
        "recordings (`ec-replay`) are **not measured yet** — they need the user's recordings; `pinch` has no HaGRID "
        "source class. M3 is code-complete, not exited.",
        "",
        "Model licence: CC BY-SA 4.0, trained on HaGRID (https://github.com/hukenovs/hagrid) — see "
        "`App/Resources/MODEL_LICENSE.md`.",
    ]
    return "\n".join(lines) + "\n"


def _local_section(m: dict) -> list[str]:
    loc, classes = m["local"], m["classes"]
    return [
        "## Your hand (personalization)",
        "",
        f"The user's own recordings were added to training ({m['sizes']['local_train_rows_incl_augmented']} rows incl. "
        f"flipped copies, counted ×{m['config'].get('local_weight', 1)}) and evaluated on the **last 25 % of each "
        f"recording** ({m['sizes']['local_test']} hands), "
        "which the model never saw. Same person, so this measures fit to the user, not generalization; the HaGRID "
        "numbers above exclude every personal row.",
        "",
        f"Accuracy acting at ≥ {m['threshold']}: **{loc['acted_accuracy']:.1%}**; "
        f"`none` hands turned into a gesture: {loc['none_false_trigger_rate']:.1%}.",
        "",
        "| Class | Recall | Support |",
        "|---|---|---|",
        *[f"| {c} | {loc['acted_recall'][c]:.3f} | {loc['support'][c]} |" for c in classes if loc["support"][c]],
        "",
        "How much the personal rows count was chosen on each recording's validation slice (the 15 % before the "
        "test part), keeping HaGRID validation gesture precision within 0.5 pt of weight 1:",
        "",
        "| Personal weight | Your val accuracy @ threshold | HaGRID val gesture precision |",
        "|---|---|---|",
        *[f"| ×{r['local_weight']} | {r['local_val_acted']:.4f} | {r['hagrid_val_precision']:.4f} |"
          for r in m["selection"].get("local_runs", [])],
        "",
    ]
