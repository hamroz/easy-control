"""Renders the evaluation metrics as Markdown."""


def render(m: dict) -> str:
    classes = m["classes"]
    lines = [
        "# M3 Evaluation Report — Pose Classifier",
        "",
        f"Generated by `tools/training/train.py` on {m['date']}. Test set = HaGRID **held-out subjects** "
        f"({m['subjects']['test']} people never seen in training).",
        "",
        "## Headline",
        "",
        "| Classifier | Test accuracy | Macro F1 |",
        "|---|---|---|",
        f"| **Core ML MLP (this model)** | **{m['test']['accuracy']:.1%}** | **{m['test']['macro_f1']:.3f}** |",
        f"| Rule-based (M2 bootstrap) | {m['rules']['accuracy']:.1%} | {m['rules']['macro_f1']:.3f} |",
        "",
        f"Target from the spec: ≥ 97 % accuracy → **{'met' if m['test']['accuracy'] >= 0.97 else 'not met'}**.",
        "",
        "## Data",
        "",
        "| Split | Samples (after gate) | Subjects |",
        "|---|---|---|",
    ]
    for split in ("train", "val", "test"):
        lines.append(f"| {split} | {m['sizes'][split]} | {m['subjects'][split]} |")
    g = m["gate"]
    lines += [
        "",
        f"Runtime gate (reliable hand, every finger known) kept {g['kept']} of {g['total']} matched hands "
        f"({g['kept'] / max(g['total'], 1):.1%}); the rest are what the app already maps to `none`.",
        "",
        "## Per class (test)",
        "",
        "| Class | Precision | Recall | F1 | Support |",
        "|---|---|---|---|---|",
    ]
    for c in classes:
        r = m["test"]["per_class"][c]
        lines.append(f"| {c} | {r['precision']:.3f} | {r['recall']:.3f} | {r['f1']:.3f} | {r['support']} |")
    lines += ["", "## Confusion matrix (test; rows = truth, columns = prediction)", "",
              "| | " + " | ".join(classes) + " |", "|---" * (len(classes) + 1) + "|"]
    for c, row in zip(classes, m["test"]["confusion"]):
        lines.append(f"| **{c}** | " + " | ".join(str(v) for v in row) + " |")
    lines += [
        "",
        "## Training",
        "",
        f"MLP 52→{m['training']['hidden'][0]}→{m['training']['hidden'][1]}→{len(classes)}, dropout 0.2, AdamW (lr 1e-3, wd 1e-4), "
        f"cross-entropy with class-weight power {m['training']['weight_power']} (chosen on the validation split; "
        f"see sweep below), "
        f"early stopping on validation macro F1 (best epoch {m['training']['best_epoch']}, "
        f"val macro F1 {m['training']['best_val_f1']:.3f}). Standardization is folded into the model.",
        "",
        f"Core ML export check: argmax agreement with PyTorch on {m['coreml_check']['n']} test samples = "
        f"{m['coreml_check']['agreement']:.1%}.",
        "",
        "### Model selection (on the validation split)",
        "",
        "| Class-weight power | Hidden | Val accuracy | Val macro F1 | Gesture precision |",
        "|---|---|---|---|---|",
        *[f"| {r[0]} | {r[1]} | {r[2]:.4f} | {r[3]:.4f} | {r[4]:.4f} |" for r in m.get("sweep", [])],
        "",
        "Gesture precision = how often a predicted gesture (not `none`) is correct; it drives false triggers, "
        "so full inverse-frequency weighting (which pushes ambiguous hands toward the rarer gesture classes) lost.",
        "Disclosure: the initial configuration (power 1.0, 128/64) was also scored on the test split before the sweep "
        "(96.8 %); the sweep and the final choice used validation metrics only.",
        "",
        "## Not yet measured",
        "",
        "- False actions per hour on real normal-use recordings (`ec-replay`) — needs the user's recordings.",
        "- `pinch` — no HaGRID source class; needs user recordings.",
        "",
        "Model licence: CC BY-SA 4.0, trained on HaGRID (https://github.com/hukenovs/hagrid).",
    ]
    return "\n".join(lines) + "\n"
